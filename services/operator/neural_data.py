def make_splits(known_titles: set[str]) -> tuple[list[tuple[str, str]], ...]:
    """Разделить данные по исходной формулировке без её повторения между частями."""
    train: list[tuple[str, str]] = []
    validation: list[tuple[str, str]] = []
    test: list[tuple[str, str]] = []
    for label, variants in VARIANTS.items():
        if label not in known_titles:
            continue
        for phrase in variants[:3]:
            train.extend((text, label) for text in (phrase, f"Проблема: {phrase}", f"Помогите: {phrase}"))
        validation.append((variants[3], label))
        test.append((variants[4], label))
    if len({label for _, label in train}) < 2:
        raise ValueError("Для обучения нужны закрытые заявки хотя бы двух типов")
    return train, validation, test
